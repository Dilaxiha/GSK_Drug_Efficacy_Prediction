from pathlib import Path

import numpy as np
import pandas as pd

INPUT_PATH = Path("dataset/clinical_data_cleaned.csv")
OUTPUT_PATH = Path("dataset/feature_engineered_clinical_data.csv")
REPORT_PATH = Path("output/feature_engineering_report.txt")

if not INPUT_PATH.exists():
    ROOT = Path(__file__).resolve().parent.parent
    INPUT_PATH = ROOT / "dataset" / "clinical_data_cleaned.csv"
    OUTPUT_PATH = ROOT / "dataset" / "feature_engineered_clinical_data.csv"
    REPORT_PATH = ROOT / "output" / "feature_engineering_report.txt"


def safe_flag(series: pd.Series, condition: pd.Series) -> pd.Series:
    """Create a float flag series while preserving missing values."""
    result = pd.Series(np.nan, index=series.index, dtype="float64")
    valid_mask = series.notna()
    result.loc[valid_mask] = condition.loc[valid_mask].astype(float)
    return result


if not INPUT_PATH.exists():
    raise FileNotFoundError(f"Input dataset not found: {INPUT_PATH}")

# Load cleaned data
# Use the file generated by the preprocessing step

df = pd.read_csv(INPUT_PATH)
input_row_count = len(df)

required_columns = {
    "egfr", "alt_enzyme", "ast_enzyme", "concurrent_drugs", "bmi", "age", "dosage",
}
missing_columns = sorted(required_columns.difference(df.columns))
if missing_columns:
    raise ValueError(f"Input dataset is missing required columns: {', '.join(missing_columns)}")

# -----------------------------------------------------------------------------
# 1. Kidney Function Category
# -----------------------------------------------------------------------------
# eGFR clinical staging: >=90 Normal, 60-89 Mild, 30-59 Moderate, <30 Severe
# Using include_lowest=True avoids edge-case boundary issues.
df["kidney_stage"] = pd.cut(
    df["egfr"],
    bins=[-np.inf, 30, 60, 90, np.inf],
    labels=["Severe", "Moderate", "Mild", "Normal"],
    right=False,
    include_lowest=True,
)

# -----------------------------------------------------------------------------
# 2. Liver Risk Flag
# -----------------------------------------------------------------------------
# ALT > 40 OR AST > 40 indicates potential liver issues
liver_condition = (df["alt_enzyme"] > 40) | (df["ast_enzyme"] > 40)
df["liver_risk"] = safe_flag(df["alt_enzyme"], liver_condition)

# -----------------------------------------------------------------------------
# 3. Polypharmacy Flag
# -----------------------------------------------------------------------------
# Taking 5+ concurrent medications increases ADR risk significantly
polypharmacy_condition = df["concurrent_drugs"] >= 5
df["polypharmacy"] = safe_flag(df["concurrent_drugs"], polypharmacy_condition)

# -----------------------------------------------------------------------------
# 4. BMI Category
# -----------------------------------------------------------------------------
df["bmi_category"] = pd.cut(
    df["bmi"],
    bins=[-np.inf, 18.5, 25, 30, np.inf],
    labels=["Underweight", "Normal", "Overweight", "Obese"],
    right=False,
    include_lowest=True,
)

# -----------------------------------------------------------------------------
# 5. Age Group
# -----------------------------------------------------------------------------
df["age_group"] = pd.cut(
    df["age"],
    bins=[0, 18, 40, 60, 80, 120],
    labels=["Pediatric", "Young Adult", "Middle Aged", "Senior", "Elderly"],
    right=False,
    include_lowest=True,
)

# -----------------------------------------------------------------------------
# 6. Drug-Age Interaction
# -----------------------------------------------------------------------------
# High-dose indicator for elderly patients (Age > 65)
median_dosage = df["dosage"].median()
elderly_condition = (df["age"] > 65) & (df["dosage"] > median_dosage)
df["elderly_high_dose"] = safe_flag(df["age"], elderly_condition)

# -----------------------------------------------------------------------------
# 7. Lab Value Ratios
# -----------------------------------------------------------------------------
# AST/ALT ratio (De Ritis ratio) > 2 suggests alcoholic liver disease.
# Keep NaN where ALT is zero or missing.
df["de_ritis_ratio"] = np.where(
    df["alt_enzyme"].notna() & (df["alt_enzyme"] != 0),
    df["ast_enzyme"] / df["alt_enzyme"],
    np.nan,
)

# -----------------------------------------------------------------------------
# Save the feature-engineered dataset
# -----------------------------------------------------------------------------
OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
df.to_csv(OUTPUT_PATH, index=False)

new_features = [
    "kidney_stage",
    "liver_risk",
    "polypharmacy",
    "bmi_category",
    "age_group",
    "elderly_high_dose",
    "de_ritis_ratio",
]

print(f"Loaded dataset shape: {df.shape}")
print(f"Saved engineered dataset to: {OUTPUT_PATH}")
print("New features added:", new_features)
print("Columns added:", len(new_features))

report_lines = [
    "FEATURE ENGINEERING REPORT",
    "=" * 26,
    f"Input: {INPUT_PATH}",
    f"Output dataset: {OUTPUT_PATH}",
    f"Input/output dimensions: {df.shape[0]:,} rows x {df.shape[1]:,} columns",
    f"Original columns: {df.shape[1] - len(new_features):,}",
    f"New feature columns: {len(new_features):,}",
    "",
    "NEW FEATURES",
    "------------",
    *[f"- {feature}" for feature in new_features],
    "",
    "VALIDATION",
    "----------",
    f"- Required source columns: PASS ({len(required_columns)} present)",
    f"- Output row count preserved: {'PASS' if len(df) == input_row_count else 'FAIL'}",
    f"- Output duplicate rows: {int(df.duplicated().sum()):,}",
    f"- Output missing values: {int(df.isna().sum().sum()):,}",
    "",
    "FEATURE VALUE SUMMARY",
    "----------------------",
]
for feature in new_features:
    values = df[feature]
    if pd.api.types.is_numeric_dtype(values):
        report_lines.append(
            f"- {feature}: missing={int(values.isna().sum()):,}, "
            f"min={values.min():.6g}, max={values.max():.6g}, mean={values.mean():.6g}"
        )
    else:
        counts = values.value_counts(dropna=False).to_dict()
        formatted_counts = ", ".join(f"{key!r}: {value:,}" for key, value in counts.items())
        report_lines.append(f"- {feature}: {formatted_counts}")

REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
REPORT_PATH.write_text("\n".join(report_lines) + "\n", encoding="utf-8")
print(f"Saved feature-engineering report to: {REPORT_PATH}")